"""Intersect the balanced-triangle test (Tomar, Corollary 9.10) with the core census.

Use the data/cells directory of the upstream sections3-5 Lean project and the
remaining.csv generated by core_census.py. The input's body indices are zero-based.
"""
import argparse
import csv
import hashlib
import json
import lzma
from collections import Counter, defaultdict
from pathlib import Path


def balanced_triangles(cell):
    """Find each triple with the required exact force minima in both trees."""
    counts = {'z': Counter(), 'w': Counter()}
    for tag, terms in cell['argmin']:
        if len(tag) != 3 or tag[:2] not in (['z', 'S'], ['w', 'S']) or len(tag[2]) != 1:
            continue
        body = tag[2][0]
        if len(terms) == 2 and all(len(e) == 3 and e[:2] == ['cross', body] for e in terms):
            triple = tuple(sorted((body, terms[0][2], terms[1][2])))
            if len(set(triple)) == 3:
                counts[tag[0]][triple] += 1
    candidates = {t for t in counts['z'].keys() & counts['w'].keys()
                  if max(counts['z'][t], counts['w'][t]) >= 2}
    for colour in ('z', 'w'):
        if not candidates:
            break
        tree = cell[colour + 'tree']
        children = tree['children']
        parents = {child: int(node) for node, branch in children.items() for child in branch}
        paths = []
        for body in range(6):
            node = tree['leaf'][str(body)]
            path = {}
            while node in parents:
                parent = parents[node]
                path[parent] = node
                node = parent
            paths.append(path)
        def has_node(t):
            a,b,c = (paths[i] for i in t)
            return any(len({a[k],b[k],c[k]}) == 3 for k in a.keys() & b.keys() & c.keys())
        candidates = {t for t in candidates if has_node(t)}
    return candidates


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cells', type=Path, required=True)
    parser.add_argument('--remaining', type=Path, required=True)
    parser.add_argument('--survivors', type=Path, help='write pairs passing both generic tests')
    args = parser.parse_args()
    manifest = {name: digest for digest, name in
                (line.split() for line in (args.cells/'SHA256SUMS').read_text().splitlines())}
    marked = defaultdict(list)
    with args.remaining.open() as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        for row in reader:
            key = int(row['tomar_class']), int(row['cell_id'])
            marked[key].append(row)
    counts = Counter()
    uncaught = []
    by_class = Counter()
    seen = set()
    seen_files = set()
    for path in sorted(args.cells.glob('c*.jsonl.xz')):
        cls = int(path.name.split('.')[0][1:])
        keyname = path.name[:-3]
        digest = hashlib.sha256()
        with lzma.open(path, 'rb') as f:
            for index, line in enumerate(f):
                digest.update(line)
                counts['catalogue cells'] += 1
                ts = balanced_triangles(json.loads(line))
                if ts:
                    counts['cells with a qualifying triple'] += 1
                if cls == 29:
                    counts['diagram 8 cells'] += 1
                    counts['diagram 8 cells with a qualifying triple'] += bool(ts)
                key = cls,index
                if key not in marked:
                    continue
                seen.add(key)
                for row in marked[key]:
                    i = int(row['variable_mass_slot_1_based']) - 1
                    subcase = ('all positive t' if any(i not in tr for tr in ts)
                               else 'outside 1/4' if ts else 'uncaught')
                    counts['core-zero pairs: ' + subcase] += 1
                    if cls == 29:
                        counts['diagram 8 core-zero pairs: ' + subcase] += 1
                    if not ts:
                        uncaught.append(row)
                        by_class[(cls, row['chang_chen_diagram'])] += 1
        if digest.hexdigest() != manifest[keyname]:
            raise ValueError(f'Cell file digest mismatch: {keyname}')
        seen_files.add(keyname)
    if seen_files != manifest.keys():
        raise ValueError('Incomplete cell files')
    if seen != marked.keys():
        raise ValueError('Some supplied cell IDs were absent from the catalogue')
    for key in sorted(counts):
        print(f'{key}: {counts[key]}')
    print('Uncaught pairs by (Tomar class, Chang–Chen diagram):',
          sorted(by_class.items()))
    if args.survivors:
        with args.survivors.open('w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=fields, lineterminator='\n')
            writer.writeheader()
            writer.writerows(uncaught)

if __name__ == '__main__':
    main()
